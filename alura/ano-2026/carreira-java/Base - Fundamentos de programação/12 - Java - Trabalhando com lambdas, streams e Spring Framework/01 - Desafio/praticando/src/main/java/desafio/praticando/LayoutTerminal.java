package desafio.praticando;

public class LayoutTerminal {
	public static void finalDeCodigo() {
		System.out.println("\n");
	}

	public static void msg(String msg) {
		System.out.println("\n");
		System.out.println("==========================================================");
		System.out.println(msg);
		System.out.println("==========================================================");
		System.out.println();
	}
}
